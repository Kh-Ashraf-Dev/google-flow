async function syncPricing() {
  for (const row of PRICING) {
    // Prices belong to the code (there's no admin screen for them), so every start syncs them.
    await db.run(`INSERT INTO pricing_rules (model_key, label, kind, credits_per_second, credits_per_second_1080p, credits_per_image, google_usd_per_unit)
      VALUES (?, ?, ?, ?, ?, ?, ?) ON CONFLICT (model_key) DO UPDATE SET label = EXCLUDED.label, kind = EXCLUDED.kind,
      credits_per_second = EXCLUDED.credits_per_second, credits_per_second_1080p = EXCLUDED.credits_per_second_1080p,
      credits_per_image = EXCLUDED.credits_per_image, google_usd_per_unit = EXCLUDED.google_usd_per_unit`, ...row)
  }
  await db.run('DELETE FROM pricing_rules WHERE NOT (model_key = ANY(?))', PRICING.map((p) => p[0]))
}

// Media made before projects existed goes into one "My first project" per person.
async function moveIntoProjects() {
  const now = Date.now()
  await tx(async () => {
    // updated_at 0: Home then sorts and dates it by its newest media, not by this migration.
    await db.run(`INSERT INTO projects (user_id, name, created_at, updated_at)
      SELECT u.id, 'My first project', ?, 0 FROM users u
      WHERE NOT EXISTS (SELECT 1 FROM projects p WHERE p.user_id = u.id) AND (
        EXISTS (SELECT 1 FROM jobs j WHERE j.user_id = u.id AND j.project_id IS NULL AND j.status != 'blocked')
        OR EXISTS (SELECT 1 FROM scenes s WHERE s.user_id = u.id AND s.project_id IS NULL)
        OR EXISTS (SELECT 1 FROM media_collections m WHERE m.user_id = u.id AND m.project_id IS NULL))`, now)
    for (const table of ['jobs', 'scenes', 'media_collections']) {
      await db.run(`UPDATE ${table} t SET project_id = (SELECT MIN(p.id) FROM projects p WHERE p.user_id = t.user_id)
        WHERE t.project_id IS NULL${table === 'jobs' ? " AND t.status != 'blocked'" : ''}`)
    }
  })
}

export async function initDb() {
  await db.exec(SCHEMA)
  await db.exec('ALTER TABLE users ADD COLUMN IF NOT EXISTS disabled BOOLEAN NOT NULL DEFAULT FALSE')
  // Jobs from one press of Generate (batch view groups them), and the part of a clip a scene plays.
  await db.exec('ALTER TABLE jobs ADD COLUMN IF NOT EXISTS batch_id INTEGER')
  await db.exec('ALTER TABLE scene_clips ADD COLUMN IF NOT EXISTS trim_start DOUBLE PRECISION, ADD COLUMN IF NOT EXISTS trim_end DOUBLE PRECISION')
  await db.exec(`
    -- A project holds its own media, scenes and collections; Home lists them.
    CREATE TABLE IF NOT EXISTS projects (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
      name TEXT NOT NULL, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS projects_user ON projects (user_id, id);
    ALTER TABLE jobs ADD COLUMN IF NOT EXISTS project_id INTEGER, ADD COLUMN IF NOT EXISTS inputs TEXT;
    -- A failed card the user removed from the gallery. The row stays for the ledger and admin.
    ALTER TABLE jobs ADD COLUMN IF NOT EXISTS dismissed_at BIGINT;
    CREATE INDEX IF NOT EXISTS jobs_project ON jobs (project_id, id);
    ALTER TABLE scenes ADD COLUMN IF NOT EXISTS project_id INTEGER;
    ALTER TABLE media_collections ADD COLUMN IF NOT EXISTS project_id INTEGER;
    ALTER TABLE assets ADD COLUMN IF NOT EXISTS favorite BOOLEAN NOT NULL DEFAULT FALSE;
    -- A name the user gives an image or video, to mention it in a prompt with @.
    ALTER TABLE assets ADD COLUMN IF NOT EXISTS name TEXT;
    -- A preset voice for a character (server/voices.ts); the voice text is extra notes on top of it.
    ALTER TABLE characters ADD COLUMN IF NOT EXISTS voice_id TEXT;
    -- A reusable person: how they look (reference images + text) and how they sound.
    CREATE TABLE IF NOT EXISTS characters (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
      name TEXT NOT NULL, look TEXT NOT NULL DEFAULT '', voice TEXT NOT NULL DEFAULT '',
      asset_ids INTEGER[] NOT NULL DEFAULT '{}', created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, deleted_at BIGINT
    );
  `)
  await moveIntoProjects()
  await seed()
  await syncPricing()
}
