// Postgres on Neon. Media files still live on disk (config.dataDir/media).
mkdirSync(join(config.dataDir, 'media'), { recursive: true })

if (!config.databaseUrl) throw new Error('DATABASE_URL is not set. Put the Neon connection string in .env.local.')

// COUNT and SUM come back as int8/numeric, which pg returns as strings; these values are
// all well inside a JS number.
pg.types.setTypeParser(20, (v) => Number(v))
pg.types.setTypeParser(1700, (v) => Number(v))

const pool = new pg.Pool({ connectionString: config.databaseUrl, max: 10, idleTimeoutMillis: 30_000 })
pool.on('error', (err) => console.error('[db] idle client error', err.message))

type Client = pg.Pool | pg.PoolClient
// Inside tx() every query goes to that transaction's client, so callers don't pass it around.
const current = new AsyncLocalStorage<pg.PoolClient>()
const client = (): Client => current.getStore() ?? pool

// Queries are written with `?` placeholders; Postgres wants $1, $2, …
function toPg(sql: string) {
  let i = 0
  return sql.replace(/\?/g, () => `$${++i}`)
}

async function query<T>(sql: string, args: unknown[]): Promise<pg.QueryResult<T & pg.QueryResultRow>> {
  return client().query<T & pg.QueryResultRow>(toPg(sql), args)
}

export const db = {
  async all<T>(sql: string, ...args: unknown[]): Promise<T[]> {
    return (await query<T>(sql, args)).rows
  },
  async get<T>(sql: string, ...args: unknown[]): Promise<T | undefined> {
    return (await query<T>(sql, args)).rows[0]
  },
  // Returns the number of rows changed.
  async run(sql: string, ...args: unknown[]): Promise<number> {
    return (await query(sql, args)).rowCount ?? 0
  },
  // INSERT … and returns the new row's id.
  async insert(sql: string, ...args: unknown[]): Promise<number> {
    return Number((await query<{ id: number }>(`${sql} RETURNING id`, args)).rows[0].id)
  },
  async exec(sql: string): Promise<void> {
    await client().query(sql)
  },
}

// Balance checks lock the wallet row (see ledger.lockWallet), so two requests can't spend
// the same credits.
export async function tx<T>(fn: () => Promise<T>): Promise<T> {
  if (current.getStore()) return fn() // already inside one
  const c = await pool.connect()
  try {
    await c.query('BEGIN')
    const out = await current.run(c, fn)
    await c.query('COMMIT')
    return out
  } catch (err) {
    await c.query('ROLLBACK').catch(() => {})
    throw err
  } finally {
    c.release()
  }
}

export async function audit(actorId: number | null, action: string, details: unknown = null) {
  await db.run('INSERT INTO audit_logs (actor_id, action, details, created_at) VALUES (?, ?, ?, ?)',
    actorId, action, details == null ? null : JSON.stringify(details), Date.now())
}

// Times are epoch milliseconds (BIGINT). Ids allow explicit values so data copied from the
// old SQLite file keeps its ids; scripts/sqlite-to-neon.mjs resets the sequences after.
const SCHEMA = `
CREATE TABLE IF NOT EXISTS departments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('employee','admin')),
  department_id INTEGER REFERENCES departments(id),
  -- NULL means no daily limit.
  daily_limit INTEGER
);
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS wallets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_type TEXT NOT NULL CHECK (owner_type IN ('org','user')), owner_id INTEGER,
  UNIQUE (owner_type, owner_id)
);
-- Append-only. A balance is always SUM(amount); rows are never updated.
CREATE TABLE IF NOT EXISTS ledger_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, wallet_id INTEGER NOT NULL REFERENCES wallets(id),
  type TEXT NOT NULL CHECK (type IN ('topup','allocation','reserve','commit','refund','adjustment')),
  amount INTEGER NOT NULL, job_id INTEGER, related_wallet_id INTEGER, reason TEXT,
  created_by INTEGER, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ledger_wallet ON ledger_entries (wallet_id, created_at);
CREATE TABLE IF NOT EXISTS pricing_rules (
  model_key TEXT PRIMARY KEY, label TEXT NOT NULL, kind TEXT NOT NULL CHECK (kind IN ('video','image')),
  credits_per_second DOUBLE PRECISION, credits_per_second_1080p DOUBLE PRECISION, credits_per_image DOUBLE PRECISION,
  google_usd_per_unit DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS policy_rules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('block','review')), active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS blocked_keywords (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, word TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS prompt_checks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, prompt TEXT NOT NULL, enhanced TEXT,
  allowed INTEGER NOT NULL, result TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS jobs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), kind TEXT NOT NULL,
  model_key TEXT NOT NULL, params TEXT NOT NULL, prompt_original TEXT NOT NULL, prompt_final TEXT,
  estimated_cost INTEGER NOT NULL, actual_cost INTEGER, google_cost_usd DOUBLE PRECISION,
  status TEXT NOT NULL, provider_operation TEXT, error TEXT, policy TEXT,
  created_at BIGINT NOT NULL, completed_at BIGINT,
  -- The clip or image a video starts from (extend / animate), and the scene it was made for.
  source_job_id INTEGER, scene_id INTEGER
);
CREATE INDEX IF NOT EXISTS jobs_user ON jobs (user_id, id);
CREATE TABLE IF NOT EXISTS assets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id INTEGER NOT NULL REFERENCES jobs(id), user_id INTEGER NOT NULL,
  file TEXT NOT NULL, mime TEXT NOT NULL, mock INTEGER NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS assets_job ON assets (job_id);
CREATE TABLE IF NOT EXISTS media_collections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
  name TEXT NOT NULL
);
ALTER TABLE assets ADD COLUMN IF NOT EXISTS deleted_at BIGINT;
ALTER TABLE media_collections ADD COLUMN IF NOT EXISTS deleted_at BIGINT;
CREATE INDEX IF NOT EXISTS media_collections_user ON media_collections (user_id, id);
CREATE TABLE IF NOT EXISTS media_collection_assets (
  collection_id INTEGER NOT NULL REFERENCES media_collections(id) ON DELETE CASCADE,
  asset_id INTEGER NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  PRIMARY KEY (collection_id, asset_id)
);
CREATE TABLE IF NOT EXISTS topup_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), amount INTEGER NOT NULL,
  reason TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','denied')),
  decided_by INTEGER, decided_amount INTEGER, decided_at BIGINT, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS audit_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id INTEGER, action TEXT NOT NULL, details TEXT, created_at BIGINT NOT NULL
);
-- Extra daily allowance granted for one day, e.g. an approved "need more today" request.
CREATE TABLE IF NOT EXISTS daily_extras (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), day_start BIGINT NOT NULL,
  amount INTEGER NOT NULL, created_by INTEGER, created_at BIGINT NOT NULL
);
-- A scene is clips played one after another, like Flow's Scenebuilder timeline.
CREATE TABLE IF NOT EXISTS scenes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id), name TEXT NOT NULL,
  created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS scene_clips (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scene_id INTEGER NOT NULL REFERENCES scenes(id) ON DELETE CASCADE,
  job_id INTEGER NOT NULL REFERENCES jobs(id), position INTEGER NOT NULL
);
`

async function seed() {
  const has = await db.get<{ n: number }>('SELECT COUNT(*) AS n FROM users')
  if (has!.n > 0) return
  const now = Date.now()
  await tx(async () => {
    const dept = (name: string) => db.insert('INSERT INTO departments (name) VALUES (?)', name)
    const media = await dept('Media')
    const social = await dept('Social')

    // Demo accounts. Password for all of them: demo1234
    const pw = hashPassword('demo1234')
    const user = (name: string, email: string, role: string, deptId: number, limit: number | null) =>
      db.insert('INSERT INTO users (name, email, password_hash, role, department_id, daily_limit) VALUES (?, ?, ?, ?, ?, ?)', name, email, pw, role, deptId, limit)
    const omar = await user('Omar Khaled', 'omar@awqaf.demo', 'admin', media, null)
    const saif = await user('Saif Sabry', 'saif@awqaf.demo', 'employee', media, 300)
    const mona = await user('Mona Nabil', 'mona@awqaf.demo', 'employee', social, 200)

    const wallet = (type: string, owner: number | null) => db.insert('INSERT INTO wallets (owner_type, owner_id) VALUES (?, ?)', type, owner)
    const entry = (w: number, type: string, amount: number, related: number | null, reason: string, by: number | null) =>
      db.run(`INSERT INTO ledger_entries (wallet_id, type, amount, related_wallet_id, reason, created_by, created_at)
        VALUES (?, ?, ?, ?, ?, ?, ?)`, w, type, amount, related, reason, by, now)
    const org = await wallet('org', null)
    await entry(org, 'topup', 120000, null, 'Monthly pool', null)
    for (const [uid, amount] of [[omar, 1000], [saif, 2000], [mona, 1000]]) {
      const w = await wallet('user', uid)
      await entry(org, 'allocation', -amount, w, 'Starting balance', omar)
      await entry(w, 'allocation', amount, org, 'Starting balance', omar)
    }

    const rule = (name: string, description: string, action: string) =>
      db.run('INSERT INTO policy_rules (name, description, action) VALUES (?, ?, ?)', name, description, action)
    await rule('No depiction of prophets or companions', 'No image or video may show the face or body of a prophet, a companion of the Prophet, or Ahl al-Bayt.', 'block')
    await rule('No imitation of scholars or public figures', 'No prompt may name or describe a real, identifiable scholar, imam, official or public figure.', 'block')
    await rule('No AI-generated Quran text', 'Quran verses must never be generated as text inside an image or video.', 'block')
    await rule('Mosques and prayer shown with respect', 'Scenes inside mosques or during prayer must be dignified and respectful.', 'review')
    await rule('Modest dress for everyone shown', 'All people shown must be dressed modestly.', 'review')

    for (const w of ['وجه النبي', 'تجسيد الأنبياء', 'صورة الصحابة', 'الصحابة', 'prophet face', 'sahaba', 'deepfake']) {
      await db.run('INSERT INTO blocked_keywords (word) VALUES (?)', w)
    }
    await audit(null, 'seed', { note: 'Demo data created' })
  })
}

